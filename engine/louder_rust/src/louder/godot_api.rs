//! The macros that turn the engine's methods into Godot classes, and the
//! switch that turns them off.
//!
//! Every data type in [`crate::louder`] is registered with Godot, and every
//! method a host may call on it is registered through [`godot_api!`]. Both are
//! decided at compile time by the feature `godot-bindings`:
//!
//! - With the feature on, [`godot_api!`] expands to `#[godot_api] impl … { … }`,
//!   which registers every `#[func]` method in it with the class its `Self`
//!   names, and the classes themselves carry a `GodotClass` derive.
//! - With the feature off, `godot_api!` expands to nothing at all. The methods
//!   it would have registered are additions for Godot alone, so dropping them
//!   loses nothing: the engine keeps its ordinary Rust API, the C interface in
//!   the crate root is the only way in, and no class is registered.
//!
//! `#[func]` is left in the source either way. `#[godot_api]` consumes it before
//! the compiler ever sees it, and when the feature is off the impl block it
//! belongs to has been removed, so neither path leaves it dangling.
//!
//! # Why the classes are not a macro too
//!
//! The obvious shape is a macro on each `struct`, wrapping the declaration and
//! standing in for `#[derive(GodotClass)] #[class(init, tool)]`. That does not
//! work here, because this crate's C header is generated by `cbindgen`, which
//! parses the source with `syn` and never expands `macro_rules`. A struct nested
//! inside a macro invocation is invisible to it, so the type simply vanishes
//! from the generated header and every C consumer of the engine breaks.
//!
//! So the structure half is written out as two attributes on each struct, which
//! `syn` reads like any other:
//!
//! ```
//! #[derive(Clone)]
//! #[cfg_attr(feature = "godot-bindings", derive(::godot::prelude::GodotClass))]
//! #[cfg_attr(feature = "godot-bindings", class(init, tool))]
//! pub struct Choice {
//!   text: String,
//! }
//! ```
//!
//! A type the engine builds itself rather than a host takes `class(tool)` and no
//! `init`, and supplies its own constructor through `IRefCounted`, so GDScript
//! cannot default-construct something with no meaningful default:
//!
//! ```
//! # #[cfg(feature = "godot-bindings")]
//! godot_api! {
//!   impl ::godot::classes::IRefCounted for LouderContext {
//!     fn init(_base: ::godot::obj::Base<::godot::classes::RefCounted>) -> Self {
//!       Self::new()
//!     }
//!   }
//! }
//! ```
//!
//! # Naming
//!
//! A `godot_api!` block is an inherent `impl` like any other, so a `#[func]`
//! method cannot share a name with a method the engine already has. Most of
//! them are written `get_*` or `set_*`, which the engine's own accessors are
//! not. The few that would collide keep the engine's name in Godot and take a
//! `gd_` prefix in Rust:
//!
//! ```
//! # #[cfg(feature = "godot-bindings")]
//! godot_api! {
//!   impl Actor {
//!     /// Whether this actor sees every hub but decides nothing.
//!     #[func(rename = "is_spectator")]
//!     pub fn gd_spectator(&self) -> bool {
//!       Actor::is_spectator(self)
//!     }
//!   }
//! }
//! ```
//!
//! There is one other rule worth knowing: a class may have only one
//! `#[godot_api]` block, since the second would register itself over the first.
//! Each class here therefore has one, and an `IRefCounted` implementation gets
//! its own.
//!
//! The `godot_api!` blocks themselves are safe to wrap, because `cbindgen`
//! ignores inherent `impl` blocks outright: it reads types and free functions,
//! nothing more.

/// Declares an `impl` block as part of a class's Godot API.
///
/// With the `godot-bindings` feature the block gets `#[godot_api]`, which
/// registers every `#[func]` method in it with the class the block's `Self`
/// names. Without the feature the block disappears, because everything in it
/// is written for Godot: the engine's own methods live in ordinary `impl`
/// blocks beside it.
#[cfg(feature = "godot-bindings")]
macro_rules! godot_api {
  ( $( #[$attr:meta] )* impl $( $rest:tt )* ) => {
    $( #[$attr] )*
    #[::godot::prelude::godot_api]
    impl $( $rest )*
  };
}

#[cfg(not(feature = "godot-bindings"))]
macro_rules! godot_api {
  ( $( #[$attr:meta] )* impl $( $rest:tt )* ) => {};
}

/// The Godot types the registered methods are written in, re-exported so that
/// the engine modules can name them without a path in every signature.
#[cfg(feature = "godot-bindings")]
pub(crate) use ::godot::builtin::{Array, GString, PackedByteArray, Variant};
#[cfg(feature = "godot-bindings")]
pub(crate) use ::godot::obj::Gd;